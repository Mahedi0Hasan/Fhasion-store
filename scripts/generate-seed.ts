/**
 * Generates supabase/seed.sql from the demo catalogue so the database and
 * the storefront's fallback data never drift apart.
 *   npx tsx scripts/generate-seed.ts
 */
import { writeFileSync } from "node:fs";
import { DEMO_CATEGORIES as CATEGORIES, DEMO_PRODUCTS as PRODUCTS } from "../src/lib/catalog";
import { SHIPPING_ZONES } from "../src/lib/shipping/zones";

const q = (v: string | null | undefined) => (v === null || v === undefined ? "null" : `'${v.replace(/'/g, "''")}'`);
const arr = (a: string[]) => `array[${a.map(q).join(", ")}]::text[]`;
const sku = (id: string, size: string) => `DM-${id.toUpperCase()}-${size}`.replace(/[^A-Z0-9-]/g, "");

const out: string[] = [
  "-- Generated by scripts/generate-seed.ts — do not edit by hand.",
  "begin;",
  "",
  "-- categories",
  ...CATEGORIES.map((c, i) => `insert into public.categories (slug, name, name_bn, sort) values (${q(c.slug)}, ${q(c.name)}, ${q(c.nameBn)}, ${i}) on conflict (slug) do update set name = excluded.name, name_bn = excluded.name_bn, sort = excluded.sort;`),
  "",
  "-- shipping zones",
  ...SHIPPING_ZONES.map((z, i) =>
    `insert into public.shipping_zones (id, label, fee_bdt, free_over_bdt, eta, sort) values (${q(z.id)}, ${q(z.label)}, ${z.feeBDT}, ${z.freeOverBDT ?? "null"}, ${q(z.eta)}, ${i}) on conflict (id) do update set label = excluded.label, fee_bdt = excluded.fee_bdt, free_over_bdt = excluded.free_over_bdt, eta = excluded.eta;`),
  "",
  "-- demo coupons",
  `insert into public.coupons (code, kind, value, min_subtotal_bdt, max_discount_bdt, expires_at) values ('WELCOME10', 'percent', 10, 3000, 2000, '2027-12-31') on conflict (code) do nothing;`,
  `insert into public.coupons (code, kind, value, min_subtotal_bdt, expires_at) values ('DEMO500', 'fixed', 500, 10000, '2027-12-31') on conflict (code) do nothing;`,
  "",
];

for (const p of PRODUCTS) {
  out.push(`-- ${p.name}`);
  out.push(
    `insert into public.products (legacy_id, slug, name, description, details, name_bn, colour_bn, description_bn, details_bn, category_id, gender, colour, colour_hex, price_bdt, sale_price_bdt, is_new, is_bestseller, popularity, created_at)
values (${q(p.id)}, ${q(p.slug)}, ${q(p.name)}, ${q(p.description)}, ${arr(p.details)}, ${q(p.bn?.name)}, ${q(p.bn?.colour)}, ${q(p.bn?.description)}, ${arr(p.bn?.details ?? [])}, (select id from public.categories where slug = ${q(p.category)}), ${q(p.gender)}, ${q(p.colour)}, ${q(p.colourHex)}, ${p.priceBDT}, ${p.salePriceBDT ?? "null"}, ${p.tags.includes("new")}, ${p.tags.includes("bestseller")}, ${p.popularity}, ${q(p.createdAt)})
on conflict (legacy_id) do update set name = excluded.name, description = excluded.description, name_bn = excluded.name_bn, colour_bn = excluded.colour_bn, description_bn = excluded.description_bn, details_bn = excluded.details_bn, price_bdt = excluded.price_bdt, sale_price_bdt = excluded.sale_price_bdt;`,
  );
  p.images.forEach((im, i) =>
    out.push(`insert into public.product_images (product_id, src, alt, fit, object_position, sort) select id, ${q(im.src)}, ${q(im.alt)}, ${q(im.fit)}, ${q(im.position)}, ${i} from public.products where legacy_id = ${q(p.id)} and not exists (select 1 from public.product_images pi join public.products pp on pp.id = pi.product_id where pp.legacy_id = ${q(p.id)} and pi.src = ${q(im.src)});`),
  );
  for (const [size, qty] of Object.entries(p.stock)) {
    out.push(`insert into public.product_variants (product_id, size, sku) select id, ${q(size)}, ${q(sku(p.id, size))} from public.products where legacy_id = ${q(p.id)} on conflict (sku) do nothing;`);
    out.push(`insert into public.inventory (variant_id, quantity) select id, ${qty} from public.product_variants where sku = ${q(sku(p.id, size))} on conflict (variant_id) do nothing;`);
  }
  out.push("");
}
out.push("commit;", "");
writeFileSync("supabase/seed.sql", out.join("\n"));
console.log(`seed.sql: ${CATEGORIES.length} categories, ${PRODUCTS.length} products`);
